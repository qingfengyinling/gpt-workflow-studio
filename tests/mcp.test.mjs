import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
import {StreamableHTTPClientTransport} from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import {Store} from '../server/store.mjs';
import {createHttp,seed} from '../server/index.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const dir=t=>{const p=fs.mkdtempSync(path.join(os.tmpdir(),'studio-mcp-'));t.after(()=>fs.rmSync(p,{recursive:true,force:true}));return p;};
test('bundled stdio server initializes and round-trips graph, proposals and UI resource',async t=>{
  const data=dir(t),client=new Client({name:'studio-test',version:'1.0.0'});
  const transport=new StdioClientTransport({command:process.execPath,args:[path.join(root,'dist/server.mjs'),'--stdio','--data',data],stderr:'pipe'});
  t.after(async()=>{await client.close();});
  await client.connect(transport);
  const tools=await client.listTools();assert.equal(tools.tools.length,10);
  assert.deepEqual(tools.tools.find(x=>x.name==='studio_apply_proposal')._meta.ui.visibility,['app']);
  const open=await client.callTool({name:'studio_open',arguments:{}});assert.equal(open.structuredContent.workflows.length,2);
  const id=open.structuredContent.workflows[0].id;
  const context=await client.callTool({name:'studio_review_context',arguments:{id}});assert.equal(context.isError,undefined);
  const before=context.structuredContent.workflow.goal;
  const p=await client.callTool({name:'studio_propose',arguments:{id,revision:context.structuredContent.revision,summary:'测试建议',patches:[{op:'set',field:'goal',value:'MCP测试目标'}]}});
  assert.equal(p.structuredContent.workflow.goal,before);assert.equal(p.structuredContent.proposals.length,1);
  const invalid=await client.callTool({name:'studio_propose',arguments:{id,revision:1,summary:'旧版',patches:[{op:'set',field:'goal',value:'旧版'}]}});assert.equal(invalid.isError,true);
  const resources=await client.listResources();assert.equal(resources.resources.length,1);
  const ui=await client.readResource({uri:resources.resources[0].uri});assert.equal(ui.contents[0].mimeType,'text/html;profile=mcp-app');assert.match(ui.contents[0].text,/序流/);assert.ok(ui.contents[0].text.length>10000);
  const exported=await client.callTool({name:'studio_export',arguments:{id}});assert.match(exported.structuredContent.markdown,/工作流交接包/);
});
test('HTTP MCP and local API share persistence; cross-origin mutation is rejected',async t=>{
  const store=new Store(dir(t));seed(store);const server=createHttp(store,{port:0});await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(()=>{server.closeAllConnections();return new Promise(resolve=>server.close(resolve));});const url=`http://127.0.0.1:${server.address().port}`;
  const client=new Client({name:'http-test',version:'1.0.0'});await client.connect(new StreamableHTTPClientTransport(new URL(url+'/mcp')));t.after(()=>client.close());
  const opened=await client.callTool({name:'studio_open',arguments:{}});const id=opened.structuredContent.workflows[0].id;
  const res=await fetch(url+'/api',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({name:'studio_open',arguments:{id}})});assert.equal(res.status,200);assert.equal((await res.json()).data.workflow.id,id);
  const evil=await fetch(url+'/api',{method:'POST',headers:{'content-type':'application/json',origin:'https://unrelated.example'},body:'{}'});assert.equal(evil.status,403);
  const plain=await fetch(url+'/api',{method:'POST',headers:{'content-type':'text/plain'},body:'{}'});assert.equal(plain.status,415);
  assert.equal((await fetch(url+'/health')).status,200);
});
